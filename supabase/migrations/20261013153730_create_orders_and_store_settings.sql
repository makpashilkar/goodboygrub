/*
# Create orders and store_settings tables for Good Boy Grub

## Purpose
Good Boy Grub is a guest-checkout shredded chicken sub shop. No customer sign-in —
the frontend talks to Supabase as the anon role for its entire lifetime. The admin
panel is protected by a passcode in the UI (not database auth). All policies must
therefore allow `anon, authenticated`.

## New Tables

### orders
- `id` (uuid, PK, default gen_random_uuid())
- `order_number` (text, unique, human-readable ticket like GBG-0001)
- `created_at` (timestamptz, default now())
- `customer_name` (text, not null)
- `phone` (text, not null)
- `address` (text, not null)
- `pincode` (text, not null)
- `address_type` (text, default 'Home')
- `special_instructions` (text, nullable)
- `items` (jsonb, not null) — array of { id, name, price, quantity, add_cheese }
- `subtotal` (numeric(10,2), not null)
- `delivery_fee` (numeric(10,2), default 0)
- `total_amount` (numeric(10,2), not null)
- `distance_km` (numeric(5,2), default 0)
- `status` (text, default 'new', check in new/preparing/dispatched/delivered/cancelled)
- `payment_method` (text, default 'gpay_whatsapp')

### store_settings
- `id` (text, PK, default 'primary')
- `is_store_open` (boolean, not null, default true)
- `daily_slot_limit` (int, not null, default 10)
- `updated_at` (timestamptz, default now())

## Security
- RLS enabled on both tables.
- All CRUD policies use `TO anon, authenticated` with `USING (true)` / `WITH CHECK (true)`
  because this is a single-tenant no-auth app where all data is intentionally public/shared.
- The admin passcode gate is enforced in the UI, not at the database level.
- Realtime publication enabled on both tables.

## Notes
1. order_number is generated by the application as GBG-XXXX format.
2. The store_settings table has a single row with id='primary'.
3. Seeded with default store settings.
*/

CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number TEXT UNIQUE,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  pincode TEXT NOT NULL,
  address_type TEXT DEFAULT 'Home',
  special_instructions TEXT,
  items JSONB NOT NULL,
  subtotal NUMERIC(10, 2) NOT NULL,
  delivery_fee NUMERIC(10, 2) DEFAULT 0.00,
  total_amount NUMERIC(10, 2) NOT NULL,
  distance_km NUMERIC(5, 2) DEFAULT 0.00,
  status TEXT DEFAULT 'new' CHECK (status IN ('new', 'preparing', 'dispatched', 'delivered', 'cancelled')),
  payment_method TEXT DEFAULT 'gpay_whatsapp'
);

CREATE TABLE IF NOT EXISTS public.store_settings (
  id TEXT PRIMARY KEY DEFAULT 'primary',
  is_store_open BOOLEAN NOT NULL DEFAULT true,
  daily_slot_limit INT NOT NULL DEFAULT 10,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

INSERT INTO public.store_settings (id, is_store_open, daily_slot_limit)
VALUES ('primary', true, 10)
ON CONFLICT (id) DO NOTHING;

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_orders" ON public.orders;
CREATE POLICY "anon_select_orders" ON public.orders FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_orders" ON public.orders;
CREATE POLICY "anon_insert_orders" ON public.orders FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_orders" ON public.orders;
CREATE POLICY "anon_update_orders" ON public.orders FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_orders" ON public.orders;
CREATE POLICY "anon_delete_orders" ON public.orders FOR DELETE
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_select_store_settings" ON public.store_settings;
CREATE POLICY "anon_select_store_settings" ON public.store_settings FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_update_store_settings" ON public.store_settings;
CREATE POLICY "anon_update_store_settings" ON public.store_settings FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
ALTER PUBLICATION supabase_realtime ADD TABLE public.store_settings;

CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders (status);
